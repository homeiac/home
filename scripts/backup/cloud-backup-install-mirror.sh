#!/bin/bash
# Install / update the USB-disk mirrors (secondary SSK, tertiary WD 2.5TB) on the backup host
#
# Usage: ./cloud-backup-install-mirror.sh [--no-enable]
#
# Copies from this repo to $CB_HOST:
#   host/cloud-backup-mirror.sh         -> /usr/local/sbin/cloud-backup-mirror.sh   (0755)
#   host/cloud-backup-mirror@.service   -> /etc/systemd/system/
#   host/cloud-backup-mirror@.timer     -> /etc/systemd/system/
#   settings from cloud-backup-common.sh -> /etc/default/cloud-backup-mirror (shared)
#                                          /etc/default/cloud-backup-mirror-<target> (per target)
# then daemon-reload and enables cloud-backup-mirror@<target>.timer for every target in TARGETS.
# Migrates the earlier single-target units (cloud-backup-mirror.service/.timer) by removing them.
#
# Targets:
#   ssk   secondary copy, SSK USB SSD (exFAT, label SSK), everything in cloud-backup/
#   wd25  tertiary copy, old WD 2.5TB USB HDD partition 2 (exFAT, label RASPBMC), Google Photos
#         excluded (does not fit), VERIFY=1 because the disk has bad sectors
#
# Idempotent: each file is only written when its content differs; prints what changed.
# Does not run a mirror; use cloud-backup-mirror-ctl.sh run <target>.
# Design: docs/plans/cloud-drive-backup-and-reclaim.md (§5.3, Phase 4)

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/cloud-backup-common.sh"
readonly HOST_DIR="$(dirname "${BASH_SOURCE[0]}")/host"
readonly TARGETS=(ssk wd25)

ENABLE=1
case "${1:-}" in
  --no-enable) ENABLE=0;;
  "") ;;
  -h|--help) sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'; exit 0;;
  *) echo "ERROR: unknown option $1"; exit 1;;
esac

CHANGED=0
# install_file <local path or -> <remote path> <mode>: write only if different
install_file() {
  local src="$1" dst="$2" mode="$3" content want have
  if [[ "$src" == - ]]; then content="$(cat)"; else content="$(cat "$src")"; fi
  want="$(printf '%s\n' "$content" | shasum -a 256 | cut -d' ' -f1)"
  have="$(cb_ssh "sha256sum '$dst' 2>/dev/null | cut -d' ' -f1" || true)"
  if [[ "$want" == "$have" ]]; then echo "  unchanged  $dst"; return 0; fi
  printf '%s\n' "$content" | cb_ssh "install -D -m $mode /dev/stdin '$dst'"
  echo "  updated    $dst"
  CHANGED=1
}

target_conf() {  # target_conf <target>: per-target settings on stdout
  case "$1" in
    ssk) cat <<CONF
# Generated by scripts/backup/cloud-backup-install-mirror.sh - do not edit here
# Secondary copy: SSK USB SSD
DEST_SERIAL=$CB_SSK_SERIAL
DEST_LABEL=$CB_SSK_LABEL
DEST_MNT=/mnt/ssk-cloud
DEST_VERSIONS=.versions
EXCLUDES=""
VERIFY=0
CONF
    ;;
    wd25) cat <<CONF
# Generated by scripts/backup/cloud-backup-install-mirror.sh - do not edit here
# Tertiary copy: old WD 2.5TB USB HDD, exFAT partition 2. Shared with other folders (left untouched).
# Bad sectors on this disk: VERIFY=1 re-reads every file after the copy. Google Photos does not fit.
DEST_SERIAL=$CB_WD25_SERIAL
DEST_LABEL=$CB_WD25_LABEL
DEST_MNT=/mnt/wd25-cloud
DEST_VERSIONS=cloud-backup-versions
EXCLUDES="gphotos/**"
VERIFY=1
CONF
    ;;
  esac
}

echo "Installing USB-disk mirrors on $CB_HOST (targets: ${TARGETS[*]})"
cb_ssh "command -v rclone >/dev/null && command -v zfs >/dev/null && modinfo exfat >/dev/null 2>&1" \
  || { echo "ERROR: host needs rclone (cloud-backup-install-rclone.sh), zfs and the exfat module"; exit 1; }

# Migrate from the single-target units
if cb_ssh "test -e /etc/systemd/system/cloud-backup-mirror.timer -o -e /etc/systemd/system/cloud-backup-mirror.service"; then
  cb_ssh "systemctl disable --now cloud-backup-mirror.timer 2>/dev/null; \
          rm -f /etc/systemd/system/cloud-backup-mirror.timer /etc/systemd/system/cloud-backup-mirror.service"
  echo "  removed    single-target cloud-backup-mirror.{service,timer} (replaced by @ templates)"
  CHANGED=1
fi

install_file "$HOST_DIR/cloud-backup-mirror.sh"        /usr/local/sbin/cloud-backup-mirror.sh           0755
install_file "$HOST_DIR/cloud-backup-mirror@.service"  /etc/systemd/system/cloud-backup-mirror@.service 0644
install_file "$HOST_DIR/cloud-backup-mirror@.timer"    /etc/systemd/system/cloud-backup-mirror@.timer   0644
install_file - /etc/default/cloud-backup-mirror 0644 <<CONF
# Generated by scripts/backup/cloud-backup-install-mirror.sh from cloud-backup-common.sh - do not edit here
# Shared settings for every mirror target
ZVOL=$CB_ZVOL
SRC_SUBDIR=cloud-backup
REPORT_DIR=$CB_REPORT_DIR
CONF
for t in "${TARGETS[@]}"; do
  target_conf "$t" | install_file - "/etc/default/cloud-backup-mirror-$t" 0644
done

[[ $CHANGED -eq 1 ]] && cb_ssh "systemctl daemon-reload"
if [[ $ENABLE -eq 1 ]]; then
  for t in "${TARGETS[@]}"; do
    cb_ssh "systemctl enable --now cloud-backup-mirror@$t.timer >/dev/null 2>&1; echo \"  timer $t: \$(systemctl is-enabled cloud-backup-mirror@$t.timer)\""
  done
fi
cb_ssh "systemctl list-timers 'cloud-backup-mirror@*' --no-pager | head -4" || true
