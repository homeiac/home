#!/bin/bash
# Install / update the SSK mirror (secondary copy) on the backup host
#
# Usage: ./cloud-backup-install-mirror.sh [--no-enable]
#
# Copies from this repo to $CB_HOST:
#   host/cloud-backup-mirror.sh       -> /usr/local/sbin/cloud-backup-mirror.sh   (0755)
#   host/cloud-backup-mirror.service  -> /etc/systemd/system/
#   host/cloud-backup-mirror.timer    -> /etc/systemd/system/
#   settings from cloud-backup-common.sh -> /etc/default/cloud-backup-mirror
# then daemon-reload and enables the timer (unless --no-enable).
#
# Idempotent: each file is only written when its content differs; prints what changed.
# Does not run a mirror; use cloud-backup-mirror-ctl.sh run.
# Design: docs/plans/cloud-drive-backup-and-reclaim.md (§5.3, Phase 4)

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/cloud-backup-common.sh"
readonly HOST_DIR="$(dirname "${BASH_SOURCE[0]}")/host"

ENABLE=1
case "${1:-}" in
  --no-enable) ENABLE=0;;
  "") ;;
  -h|--help) sed -n '2,16p' "$0" | sed 's/^# \{0,1\}//'; exit 0;;
  *) echo "ERROR: unknown option $1"; exit 1;;
esac

# install_file <local path or -> <remote path> <mode>: write only if different
install_file() {
  local src="$1" dst="$2" mode="$3" content
  if [[ "$src" == - ]]; then content="$(cat)"; else content="$(cat "$src")"; fi
  local want; want="$(printf '%s\n' "$content" | shasum -a 256 | cut -d' ' -f1)"
  local have; have="$(cb_ssh "sha256sum '$dst' 2>/dev/null | cut -d' ' -f1" || true)"
  if [[ "$want" == "$have" ]]; then echo "  unchanged  $dst"; return 0; fi
  printf '%s\n' "$content" | cb_ssh "install -D -m $mode /dev/stdin '$dst'"
  echo "  updated    $dst"
  CHANGED=1
}

CHANGED=0
echo "Installing SSK mirror on $CB_HOST"
install_file "$HOST_DIR/cloud-backup-mirror.sh"      /usr/local/sbin/cloud-backup-mirror.sh         0755
install_file "$HOST_DIR/cloud-backup-mirror.service" /etc/systemd/system/cloud-backup-mirror.service 0644
install_file "$HOST_DIR/cloud-backup-mirror.timer"   /etc/systemd/system/cloud-backup-mirror.timer   0644
install_file - /etc/default/cloud-backup-mirror 0644 <<CONF
# Generated by scripts/backup/cloud-backup-install-mirror.sh from cloud-backup-common.sh - do not edit here
ZVOL=$CB_ZVOL
SSK_SERIAL=$CB_SSK_SERIAL
SSK_LABEL=$CB_SSK_LABEL
SSK_MNT=/mnt/ssk-cloud
SNAP_MNT=/mnt/cloud-backup-snap
SRC_SUBDIR=cloud-backup
REPORT_DIR=$CB_REPORT_DIR
CONF

cb_ssh "command -v rclone >/dev/null && command -v zfs >/dev/null && modinfo exfat >/dev/null 2>&1" \
  || { echo "ERROR: host needs rclone (cloud-backup-install-rclone.sh), zfs and the exfat module"; exit 1; }
[[ $CHANGED -eq 1 ]] && cb_ssh "systemctl daemon-reload"
if [[ $ENABLE -eq 1 ]]; then
  cb_ssh "systemctl enable --now cloud-backup-mirror.timer >/dev/null 2>&1; systemctl is-enabled cloud-backup-mirror.timer"
fi
cb_ssh "systemctl list-timers cloud-backup-mirror.timer --no-pager | head -2 || true"
